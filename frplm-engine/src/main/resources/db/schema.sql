CREATE TABLE IF NOT EXISTS LOREBOOKS
(
    id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created           TIMESTAMP             DEFAULT CURRENT_TIMESTAMP NOT NULL,
    name              VARCHAR(255) NOT NULL,
    default_outlet_id INT REFERENCES OUTLET (id),
    next_entry_id     INT          NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS ENTRY
(
    lorebook_id               INT      NOT NULL,
    entry_id                  INT      NOT NULL,
    name                      VARCHAR(255),
    enabled                   bool     NOT NULL DEFAULT TRUE,
    content                   TEXT,

    -- Injection requirements
    probability               smallint NOT NULL default 100,
    outlet                    INT      NOT NULL REFERENCES OUTLET (id),
    delay                     INT      NOT NULL default 0,
    cooldown                  INT      NOT NULL default 0,
    stick_through             INT      NOT NULL default 0,

    -- Injection options
    position                  smallint NOT NULL default 100,
    group_id                  smallint          default null,

    -- Activation strategy
    strategy                  smallint NOT NULL default 0,
    embed_text                TEXT,
    prevent_further_recursion bool     NOT NULL default false,
    non_recursable            bool     NOT NULL default false,
    delay_until_recursion     bool     NOT NULL default false,

    scan_depth                smallint          default null,

    CONSTRAINT chk_valid_position CHECK position >= 0,
    UNIQUE (name, lorebook_id),
    CONSTRAINT chk
        PRIMARY KEY (lorebook_id, entry_id),
    FOREIGN KEY (lorebook_id) REFERENCES LOREBOOKS (id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS KEYWORD
(
    id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    is_regex BOOL                NOT NULL DEFAULT FALSE,
    keyword  VARCHAR(255) UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS ENTRY_KEYWORDS
(
    lorebook_id INT NOT NULL REFERENCES LOREBOOKS (id),
    entry_id    INT NOT NULL,
    keyword_id  INT NOT NULL REFERENCES KEYWORD (id),

    PRIMARY KEY (lorebook_id, entry_id, keyword_id),
    FOREIGN KEY (lorebook_id, entry_id) REFERENCES ENTRY (lorebook_id, entry_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS entriesByKeywords ON ENTRY_KEYWORDS (keyword_id);

