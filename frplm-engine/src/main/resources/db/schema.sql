);

CREATE TABLE IF NOT EXISTS PROMPT_TEMPLATE
(
    id                  smallint     NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connection_id       INT REFERENCES LLM_CONNECTION (id),
    name                VARCHAR(300) NOT NULL UNIQUE,

    --Generation config
    streaming           bool         NOT NULL default false,

    --Gen params
    temperature         float4       NOT NULL DEFAULT 1,
    top_p               float4       NOT NULL default 0.95,
    frequency_penalty   float4       NOT NULL default 0,
    presence_penalty    float4       NOT NULL default 0,
    repetition_penalty  float4       NOT NULL default 0,
    top_k               int          NOT NULL default 0,

    -- Reasoning
    exclude_reasoning   bool         NOT NULL default true,
    reasoning_effort    smallint     NOT NULL,

    -- Prompt budgeting
    max_tokens          INT          NOT NULL DEFAULT 8192,
    lorebooks_budget    FLOAT4       NOT NULL DEFAULT 0.3,
    chat_history_budget FLOAT4       NOT NULL DEFAULT 0.4,

    next_section_id     smallint     NOT NULL default 0,

    CONSTRAINT chk_prompt_template_max_tokens
        CHECK (max_tokens > 0),

    CONSTRAINT chk_prompt_template_temperature
        CHECK (temperature >= 0 AND temperature <= 2),

    CONSTRAINT chk_prompt_template_top_p
        CHECK (top_p >= 0 AND top_p <= 1),

    CONSTRAINT chk_prompt_template_frequency_penalty
        CHECK (frequency_penalty >= -2 AND frequency_penalty <= 2),

    CONSTRAINT chk_prompt_template_presence_penalty
        CHECK (presence_penalty >= -2 AND presence_penalty <= 2),

    CONSTRAINT chk_prompt_template_repetition_penalty
        CHECK (repetition_penalty >= 0 AND repetition_penalty <= 2),

    CONSTRAINT chk_prompt_template_top_k
        CHECK (top_k >= 0),

    CONSTRAINT chk_prompt_template_reasoning_effort
        CHECK (reasoning_effort IS NULL OR reasoning_effort IN (0, 1, 2, 3, 4, 5)),

    CONSTRAINT chk_prompt_template_next_section_id
        CHECK (next_section_id >= 0),

    CONSTRAINT chk_lorebook_budget
        CHECK (lorebooks_budget BETWEEN 0.0 AND 1.0),
    CONSTRAINT chk_history_budget
        CHECK (chat_history_budget BETWEEN 0.0 AND 1.0)
);

CREATE TABLE IF NOT EXISTS PROMPT_SECTION
(
    prompt_id  smallint     NOT NULL REFERENCES PROMPT_TEMPLATE (id),
    section_id SMALLINT     NOT NULL,
    name       VARCHAR(128) NOT NULL UNIQUE,
    position   SMALLINT     NOT NULL UNIQUE,

    at_depth   int, -- Overrides position and instead renders it at a certain chat depth.

    active     boolean      NOT NULL default true,
    role       VARCHAR(9)   NOT NULL DEFAULT 'user',
    content    TEXT         NOT NULL DEFAULT ' ',

    PRIMARY KEY (prompt_id, section_id),
    CONSTRAINT chk_unique_name_per_template
        UNIQUE (prompt_id, section_id, name),
    CONSTRAINT chk_unique_position_per_section
        UNIQUE (prompt_id, section_id, position)
);

