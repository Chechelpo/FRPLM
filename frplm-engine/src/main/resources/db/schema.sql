-- ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
-- Dynamic info (actual messages)
-- ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
CREATE TABLE IF NOT EXISTS sessions
(
    id              INT          NOT NULL GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255) NOT NULL,

    world_id        INT          NOT NULL REFERENCES WORLDS (id) ON DELETE CASCADE,
    main_prompt     INT REFERENCES PROMPT_TEMPLATE (id),
    user_persona_id INT          NOT NULL REFERENCES CHARACTERS (id) ON DELETE CASCADE, -- User character ID
    current_tick    INT          NOT NULL DEFAULT 0                                     -- Incrementing for handing down ids to messages
);


CREATE TABLE IF NOT EXISTS messages
(
    session_id      INT        NOT NULL REFERENCES SESSIONS (id) ON DELETE CASCADE,
    tick_num        INT        NOT NULL,

    role            varchar(9) NOT NULL CHECK (role = 'user' OR role = 'assistant'),
    request_json    TEXT,                                                         -- Stored, but it could also just be regen. Should only be there for assistant msgs
    content         TEXT,                                                         -- Always derived

    time            INT        NOT NULL,
    world_id        INT        NOT NULL REFERENCES WORLDS (id) ON DELETE CASCADE, -- Derived
    location_id     INT        NOT NULL,                                          -- Derived

    active_response SMALLINT   NOT NULL DEFAULT 0,                                -- ID of the response that's currently active
    response_num    SMALLINT   NOT NULL DEFAULT 0,                                -- Response num counter to assign keys.

    CONSTRAINT pk_messages PRIMARY KEY (session_id, tick_num),
    CONSTRAINT fk_message_location FOREIGN KEY (location_id, world_id) REFERENCES LOCATIONS (id, world_id) ON DELETE CASCADE,
    CONSTRAINT request_json_only_for_generated_messages CHECK (request_json IS NULL OR role = 'assistant')
);

CREATE TABLE IF NOT EXISTS extras
(
    session_id   INT  NOT NULL REFERENCES SESSIONS (id) ON DELETE CASCADE,
    tick_num     INT  NOT NULL,
    extension_id VARCHAR(255) REFERENCES EXTENSION (id) ON DELETE CASCADE,

    position     int  NOT NULL,
    content      TEXT NOT NULL,

    CONSTRAINT pk_extras PRIMARY KEY (session_id, tick_num, extension_id),
    CONSTRAINT fk_extras_message FOREIGN KEY (session_id, tick_num) references MESSAGES (session_id, tick_num) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS responses
(
    session_id       INT      NOT NULL REFERENCES SESSIONS (id) ON DELETE CASCADE,
    tick_num         INT      NOT NULL,
    response_num     SMALLINT NOT NULL,

    location_id      INT      NOT NULL,
    world_id         INT      NOT NULL REFERENCES WORLDS (id) ON DELETE CASCADE,

    advances_time_by INT      NOT NULL,
    content          TEXT     NOT NULL,

    CONSTRAINT pk_responses PRIMARY KEY (session_id, tick_num, response_num),
    CONSTRAINT fk_responses_locations FOREIGN KEY (location_id, world_id) REFERENCES LOCATIONS (id, world_id) ON DELETE CASCADE,

    CONSTRAINT fk_responses_messages FOREIGN KEY (session_id, tick_num)
        REFERENCES messages (session_id, tick_num)
        ON DELETE CASCADE
);

-- MOVEMENT TRACKER ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
CREATE TABLE IF NOT EXISTS response_location_changes
(
    session_id   INT      NOT NULL,
    tick_num     INT      NOT NULL,
    response_num SMALLINT NOT NULL,

    character_id INT      NOT NULL REFERENCES characters (id) ON DELETE CASCADE,

    -- Location after applying this response
    world_id     INT      NOT NULL,
    location_id  INT      NOT NULL,

    CONSTRAINT pk_response_location_changes PRIMARY KEY (
                                                         session_id,
                                                         tick_num,
                                                         response_num,
                                                         character_id
        ),

    CONSTRAINT fk_response_location_changes_response FOREIGN KEY (
                                                                  session_id,
                                                                  tick_num,
                                                                  response_num
        )
        REFERENCES responses (
                              session_id,
                              tick_num,
                              response_num
            )
        ON DELETE CASCADE,

    CONSTRAINT fk_response_location_changes_location FOREIGN KEY (location_id, world_id)
        REFERENCES locations (id, world_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS MOVEMENTS
(
    session_id           INT NOT NULL REFERENCES SESSIONS (id) ON DELETE CASCADE,
    at_tick              INT NOT NULL,

    character_id         INT NOT NULL REFERENCES CHARACTERS (id) ON DELETE CASCADE,

    -- Location before this particular response moved the character.
    world_id             INT NOT NULL REFERENCES WORLDS (id) ON DELETE CASCADE,
    previous_location_id INT NOT NULL,

    CONSTRAINT pk_movements PRIMARY KEY (session_id, at_tick, character_id),
    CONSTRAINT fk_movements_locations FOREIGN KEY (previous_location_id, world_id) references LOCATIONS (id, world_id) ON DELETE CASCADE,
    CONSTRAINT fk_movements_messages FOREIGN KEY (session_id, at_tick) references MESSAGES (session_id, tick_num) ON DELETE CASCADE
);

-- CACHE TABLE, current linear history locations (only accounts for active responses)
CREATE TABLE IF NOT EXISTS CURRENT_LOCATIONS
(
    session_id   INT NOT NULL REFERENCES SESSIONS (id) ON DELETE CASCADE,
    tick_num     INT NOT NULL,                                              -- When did this guy reach this location? (In message tick). Isn't necessarily the last message tick.

    character_id INT NOT NULL REFERENCES CHARACTERS (id) ON DELETE CASCADE, -- who

    world_id     INT NOT NULL REFERENCES WORLDS (id) ON DELETE CASCADE,     -- where
    location_id  INT NOT NULL,

    CONSTRAINT pk_current_locations PRIMARY KEY (session_id, character_id),
    CONSTRAINT fk_current_locations_location FOREIGN KEY (location_id, world_id) REFERENCES LOCATIONS (id, world_id) ON DELETE CASCADE,
    CONSTRAINT fk_current_locations_message FOREIGN KEY (session_id, tick_num) REFERENCES MESSAGES (session_id, tick_num) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS TOKENIZER_CACHE
(
    tokenizer_id        VARCHAR(128) NOT NULL,
    tokenizer_revision  VARCHAR(128) NOT NULL,
    tokenization_mode   VARCHAR(32)  NOT NULL DEFAULT 'RAW_TEXT',

    content_hash        CHAR(64)     NOT NULL,
    content_byte_length INT          NOT NULL,

    token_count         INT          NOT NULL,

    created             TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    hit_count           BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT pk_tokenizer_cache PRIMARY KEY
        (
         tokenizer_id,
         tokenizer_revision,
         tokenization_mode,
         content_hash
            ),

    CONSTRAINT chk_tokenizer_cache_count
        CHECK (token_count >= 0),

    CONSTRAINT chk_tokenizer_cache_byte_length
        CHECK (content_byte_length >= 0)
);

CREATE INDEX IF NOT EXISTS tokenizer_cache_last_used
    ON TOKENIZER_CACHE (last_used);