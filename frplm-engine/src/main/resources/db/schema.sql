CREATE TABLE IF NOT EXISTS WORLDS
(
    id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(255) UNIQUE NOT NULL,
    description      TEXT DEFAULT ''     NOT NULL,

    lorebook_id      INT                 NOT NULL REFERENCES LOREBOOKS (id),

    -- Counters
    next_location_id INT  DEFAULT 0      NOT NULL,
    next_region_id   INT  DEFAULT 0      NOT NULL
);

CREATE TABLE IF NOT EXISTS REGION
(
    world_id         INT          NOT NULL REFERENCES WORLDS (id) ON DELETE CASCADE,
    id               INT          NOT NULL,

    parent_region_id INT,

    name             VARCHAR(255) NOT NULL,
    description      TEXT         NOT NULL DEFAULT '',
    lorebook_id      INT          NOT NULL REFERENCES LOREBOOKS (id) ON DELETE CASCADE,

    PRIMARY KEY (world_id, id),

    CONSTRAINT fk_region_parent
        FOREIGN KEY (world_id, parent_region_id)
            REFERENCES REGION (world_id, id)
            ON DELETE SET NULL,

    CONSTRAINT uq_region_name_per_world
        UNIQUE (world_id, name),

    CONSTRAINT chk_region_not_own_parent
        CHECK (parent_region_id IS NULL OR parent_region_id <> id)
);

CREATE TABLE IF NOT EXISTS LOCATIONS
(
    --PK
    id          INT             NOT NULL,
    world_id    INT             NOT NULL REFERENCES WORLDS (id) ON DELETE CASCADE,

    region_id   INT,

    --Location info
    name        VARCHAR(255)    NOT NULL,
    description TEXT DEFAULT '' NOT NULL,
    lorebook_id INT             NOT NULL REFERENCES LOREBOOKS (id),

    PRIMARY KEY (world_id, id),
    UNIQUE (world_id, region_id, name),
    CONSTRAINT fk_region FOREIGN KEY (world_id, region_id) REFERENCES REGION (world_id, id) ON DELETE CASCADE,
    CONSTRAINT unique_location_name_per_world UNIQUE (name, world_id)
);

CREATE TABLE IF NOT EXISTS starting_locations
(
    character_id INT                   NOT NULL,
    world_id     INT                   NOT NULL,
    location_id  INT                   NOT NULL,

    is_static    BOOLEAN DEFAULT FALSE NOT NULL,

    reason_why   TEXT,                    --Why the character is there, not the reason why its static
    ttl          INT     DEFAULT 0,

    PRIMARY KEY (character_id, world_id), --At most one starting location per character per world. Characters are NOT archetypes
    FOREIGN KEY (character_id) REFERENCES characters (id) ON DELETE CASCADE,
    FOREIGN KEY (world_id, location_id) REFERENCES LOCATIONS (world_id, id) ON DELETE CASCADE,
    FOREIGN KEY (world_id) REFERENCES WORLDS (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS location_edges
(
    world_id                     INT  NOT NULL,
    from_location_id             INT  NOT NULL,
    to_location_id               INT  NOT NULL,

    traversable                  bool NOT NULL DEFAULT TRUE,
    edgeDescription              TEXT,
    show_destination_name        bool NOT NULL DEFAULT TRUE,
    show_destination_description bool NOT NULL DEFAULT FALSE,

    CONSTRAINT pk_location_edges PRIMARY KEY (world_id, from_location_id, to_location_id),
    CONSTRAINT fk_location_edges_worldId FOREIGN KEY (world_id) REFERENCES WORLDS (id) ON DELETE CASCADE,
    CONSTRAINT fk_location_edges_fromLocationId FOREIGN KEY (world_id, from_location_id) REFERENCES LOCATIONS (world_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_location_edges_toLocationId FOREIGN KEY (world_id, to_location_id) REFERENCES LOCATIONS (world_id, id) ON DELETE CASCADE,
    CONSTRAINT chk_duplicates CHECK (from_location_id <> to_location_id) --We disallow self edges
);


