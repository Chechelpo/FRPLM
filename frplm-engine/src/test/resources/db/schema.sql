    background_visible          BOOLEAN          DEFAULT TRUE      NOT NULL,
    background_transform_locked BOOLEAN          DEFAULT TRUE      NOT NULL,
    background_aspect_locked    BOOLEAN          DEFAULT TRUE      NOT NULL,
