    CONSTRAINT chk_prolog_argument_position
        CHECK (position >= 0),

    CONSTRAINT chk_prolog_argument_type
        CHECK (
            type IN (
                     'CHARACTER',
                     'LOCATION',
                     'WORLD',
                     'REGION',
                     'TAG',
                     'ENTRY',
                     'INTEGER',
