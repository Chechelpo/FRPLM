CREATE TABLE IF NOT EXISTS MOVEMENTS
(
    session_id           INT NOT NULL REFERENCES SESSIONS (id) ON DELETE CASCADE,
    at_tick              INT NOT NULL, -- When did this character leave this location.

    ses_character_id     INT NOT NULL,

    -- Location before this particular response moved the character.
    world_id             INT NOT NULL REFERENCES WORLDS (id) ON DELETE CASCADE,
    previous_location_id INT NOT NULL,

    CONSTRAINT pk_movements PRIMARY KEY (session_id, at_tick, ses_character_id),

    CONSTRAINT fk_movements_locations FOREIGN KEY (world_id, previous_location_id) references LOCATIONS (world_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_movements_messages FOREIGN KEY (session_id, at_tick) references MESSAGES (session_id, tick_num) ON DELETE CASCADE,
    CONSTRAINT fk_movements_to_characters FOREIGN KEY (session_id, ses_character_id)
        references SESSION_CHARACTERS (session_id, id) ON DELETE CASCADE
);

