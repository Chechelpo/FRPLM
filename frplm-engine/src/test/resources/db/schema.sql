    next_character_id           INT              DEFAULT 0         NOT NULL,
    next_region_id              INT              DEFAULT 0         NOT NULL,

    CONSTRAINT chk_world_background_geometry
        CHECK (
            (
                background_x IS NULL
                    AND background_y IS NULL
                    AND background_width IS NULL
                    AND background_height IS NULL
                )
                OR
            (
                background_x IS NOT NULL
                    AND background_y IS NOT NULL
                    AND background_width IS NOT NULL
                    AND background_height IS NOT NULL
                    AND background_width > 0
                    AND background_height > 0
                )
            ),

    CONSTRAINT chk_world_background_opacity
        CHECK (background_opacity >= 0.0 AND background_opacity <= 1.0),

    CONSTRAINT chk_world_background_fit CHECK (background_fit IN ('CONTAIN', 'COVER'))
);

