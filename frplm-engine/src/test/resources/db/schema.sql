    lorebook_id                 INT                                NOT NULL REFERENCES LOREBOOKS (id),

    -- World-space background placement.
    --
    -- All four geometry fields are NULL when no placement is configured.
    -- The WebP itself remains in the asset store.
    background_x                DOUBLE PRECISION,
    background_y                DOUBLE PRECISION,
    background_width            DOUBLE PRECISION,
    background_height           DOUBLE PRECISION,

    -- Background rendering and editing behavior.
