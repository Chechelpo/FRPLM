DROP TABLE IF EXISTS REGION CASCADE;
CREATE TABLE IF NOT EXISTS REGION
(
    world_id                 INT              NOT NULL REFERENCES WORLDS (id) ON DELETE CASCADE,
    id                       INT              NOT NULL,

    parent_region_id         INT,

    name                     VARCHAR(255)     NOT NULL,
    description              TEXT             NOT NULL DEFAULT '',
    lorebook_id              INT              NOT NULL REFERENCES LOREBOOKS (id) ON DELETE CASCADE,

    locked                   boolean          NOT NULL DEFAULT FALSE, -- If it can be moved around in the graph
    -- Graph geometry, relative to the parent region.
    x                        DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    y                        DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    width                    DOUBLE PRECISION NOT NULL DEFAULT 100.0,
    height                   DOUBLE PRECISION NOT NULL DEFAULT 100.0,

    -- Region-background rendering behavior.
    background_opacity       DOUBLE PRECISION          DEFAULT 1.0 NOT NULL,
    background_visible       BOOLEAN                   DEFAULT TRUE NOT NULL,
    background_aspect_locked BOOLEAN                   DEFAULT TRUE NOT NULL,
    background_fit           VARCHAR(16)               DEFAULT 'CONTAIN' NOT NULL,

    -- Persist this only if collapse is part of the shared authored layout.
    collapsed                BOOLEAN                   DEFAULT FALSE NOT NULL,

    PRIMARY KEY (world_id, id),

    CONSTRAINT fk_region_parent
        FOREIGN KEY (world_id, parent_region_id)
            REFERENCES REGION (world_id, id)
            ON DELETE SET NULL,

    CONSTRAINT uq_region_name_per_world
        UNIQUE (world_id, name),

    CONSTRAINT chk_region_not_own_parent
        CHECK (
            parent_region_id IS NULL
                OR parent_region_id <> id
            ),

    CONSTRAINT chk_region_positive_size
        CHECK (
            width > 0
                AND height > 0
            ),

    CONSTRAINT chk_region_background_opacity
        CHECK (
            background_opacity >= 0.0
                AND background_opacity <= 1.0
            ),

    CONSTRAINT chk_region_background_fit
        CHECK (
            background_fit IN ('CONTAIN', 'COVER')
            )
);

