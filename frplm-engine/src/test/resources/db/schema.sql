DROP TABLE IF EXISTS PROLOG_PREDICATE CASCADE;
CREATE TABLE IF NOT EXISTS PROLOG_PREDICATE
(
    id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name         VARCHAR(128) NOT NULL,
    arity        SMALLINT     NOT NULL DEFAULT 0,

    -- SYSTEM: facts supplied by Java
    -- USER: predicate defined by user-written Prolog clauses
    -- BUILTIN: safe tuProlog predicate exposed in the editor
    kind         VARCHAR(16)  NOT NULL,
    -- Signal to add clauses for type checking at runtime.
    -- Ex.: character/2 character, character transforms into
    -- fears(X, Y):-
    --      character(X), character(Y), fears(X,C), fears(C,Y).
    type_check   BOOLEAN      NOT NULL DEFAULT FALSE,

    -- Used only for SYSTEM predicates.
    -- Maps the predicate to a Java fact provider.
    provider_key VARCHAR(128),

    -- Used only for USER predicates.
    -- May contain one or more Prolog clauses.
    source       TEXT,

    description  TEXT         NOT NULL DEFAULT '',
    enabled      BOOLEAN      NOT NULL DEFAULT TRUE,

    CONSTRAINT uq_prolog_predicate_name_per_arity UNIQUE (name, arity),

    CONSTRAINT chk_prolog_predicate_arity
        CHECK (arity >= 0),

    CONSTRAINT chk_prolog_predicate_kind
        CHECK (kind IN ('SYSTEM', 'USER', 'BUILTIN')),

    CONSTRAINT chk_prolog_predicate_source
        CHECK (
            (kind = 'SYSTEM' AND provider_key IS NOT NULL AND source IS NULL)
                OR
            (kind = 'USER' AND source IS NOT NULL AND provider_key IS NULL)
                OR
            (kind = 'BUILTIN' AND source IS NULL AND provider_key IS NULL)
            )
);

DROP TABLE IF EXISTS PROLOG_PREDICATE_ARGUMENT CASCADE;
CREATE TABLE IF NOT EXISTS PROLOG_PREDICATE_ARGUMENT
(
    predicate_id INT         NOT NULL
